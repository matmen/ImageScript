# Writes src/codecs/av1/fdct-lee.ts: the unnormalized 4-, 8- and 16-point DCT-IIs of src/codecs/av1/fdct.ts's recursion
# (Lee's) as straight-line code (the same operations, on locals instead of scratch arrays):
#   python scripts/av1-fdct.py > src/codecs/av1/fdct-lee.ts
import math
counter = [0]
lines = []
def tmp(expr):
    name = f't{counter[0]}'
    counter[0] += 1
    lines.append(f'    const {name} = {expr};')
    return name

# 1 / (2 cos(pi (2i + 1) / 2n))
twiddle = lambda i, n: repr(1 / (2 * math.cos(math.pi * (2 * i + 1) / (2 * n))))

def dct(x):
    n = len(x)
    if n == 2:
        return [tmp(f'{x[0]} + {x[1]}'), tmp(f'({x[0]} - {x[1]}) * {twiddle(0, 2)}')]
    half = n // 2
    a = [tmp(f'{x[i]} + {x[n - 1 - i]}') for i in range(half)]
    b = [tmp(f'({x[i]} - {x[n - 1 - i]}) * {twiddle(i, n)}') for i in range(half)]
    even, odd = dct(a), dct(b)
    out = [None] * n
    for k in range(half):
        out[2 * k] = even[k]
        out[2 * k + 1] = tmp(f'{odd[k]} + {odd[k + 1]}') if k + 1 < half else odd[k]
    return out

print('''/*!
 * Generated by scripts/av1-fdct.py: the 4-, 8- and 16-point DCTs of fdct.ts's recursion, unrolled
 */''')
for n in (4, 8, 16):
    counter[0] = 0; lines.clear()
    at = lambda i: f'x[o + {i}]' if i else 'x[o]'
    out = dct([at(i) for i in range(n)])
    print(f'\n// the unnormalized {n}-point DCT-II of x[o] in place')
    print(f'export function dct{n}(x: Float64Array, o: number): void {{')
    for l in lines: print(l)
    for i in range(n): print(f'    {at(i)} = {out[i]};')
    print('}')
