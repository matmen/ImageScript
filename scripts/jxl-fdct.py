# Writes src/codecs/jxl/fdct.ts: the forward 8- to 64-point DCTs of src/codecs/jxl/dct.ts's recursion as
# straight-line code (the same operations in the same order, on locals instead of scratch arrays):
#   python scripts/jxl-fdct.py > src/codecs/jxl/fdct.ts
counter = [0]
lines = []
def tmp(expr):
    counter[0] += 1
    name = f't{counter[0]}'
    lines.append(f'    const {name} = {expr};')
    return name

def fdct(vals, n):
    # vals: list of expressions (locals) of length n; returns list of result names
    if n == 4:
        i0, i1, i2, i3 = vals
        s03 = tmp(f'{i0} + {i3}'); s12 = tmp(f'{i1} + {i2}')
        t0 = tmp(f'({i0} - {i3}) * SEC0'); t1 = tmp(f'({i1} - {i2}) * SEC1')
        o0 = tmp(f'({t0} + {t1}) / 4'); o1 = tmp(f'({t0} - {t1}) / 4')
        return [tmp(f'({s03} + {s12}) / 4'), tmp(f'{o0} * Math.SQRT2 + {o1}'), tmp(f'({s03} - {s12}) / 4'), o1]
    half = n // 2
    a = [tmp(f'({vals[i]} + {vals[n - i - 1]}) / 2') for i in range(half)]
    b = [tmp(f'({vals[i]} - {vals[n - i - 1]}) / 2 * SEC{n}[{i}]') for i in range(half)]
    a = fdct(a, half)
    b = fdct(b, half)
    # b[0] *= sqrt 2, then b[i] += b[i + 1] (ascending: each adds the original)
    b = list(b)
    b[0] = tmp(f'{b[0]} * Math.SQRT2')
    b = [tmp(f'{b[i]} + {b[i + 1]}') for i in range(half - 1)] + [b[half - 1]]
    out = [None] * n
    for i in range(half):
        out[2 * i] = a[i]
        out[2 * i + 1] = b[i]
    return out

print('''/*!
 * Generated by scripts/jxl-fdct.py: the forward 8- to 64-point DCTs of dct.ts, unrolled (its recursion is ported
 * from jxl-oxide, crates/jxl-render/src/vardct/generic/dct.rs; Copyright (c) Wonwoo Choi, MIT License, see
 * THIRD_PARTY_NOTICES.md)
 */

const SEC0 = 0.5411961, SEC1 = 1.306563;
// 1 / (2 cos((2k + 1) pi / 2n))
const secants = (n: number): Float64Array => Float64Array.from({ length: n / 2 }, (_, k) => 1 / Math.cos((2 * k + 1) / (2 * n) * Math.PI) / 2);
const SEC8 = secants(8), SEC16 = secants(16), SEC32 = secants(32), SEC64 = secants(64);
''')
for n in (8, 16, 32, 64):
    counter[0] = 0; lines.clear()
    vals = [f'v{i}' for i in range(n)]
    out = fdct(vals, n)
    print(f'// the forward {n}-point DCT of buf[o + k * step] in place (generated: dct\'s recursion, unrolled)')
    print(f'export function fdct{n}(buf: Float32Array | Float64Array, o: number, step: number): void {{')
    for i in range(n):
        print(f'    const v{i} = buf[o + {i} * step];' if i else '    const v0 = buf[o];')
    for l in lines: print(l)
    for i in range(n):
        print(f'    buf[o + {i} * step] = {out[i]};' if i else f'    buf[o] = {out[0]};')
    print('}')
    print()
