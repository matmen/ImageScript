# Writes src/codecs/jxl/idct.ts: the inverse 16- and 32-point DCTs of src/codecs/jxl/dct.ts's recursion as straight-line
# code (the same operations in the same order, on locals instead of scratch arrays):
#   python scripts/jxl-idct.py > src/codecs/jxl/idct.ts
counter = [0]
lines = []
def tmp(expr):
    counter[0] += 1
    name = f't{counter[0]}'
    lines.append(f'    const {name} = {expr};')
    return name

def idct(vals, n, secname):
    # vals: list of expressions (locals) of length n; returns list of result names
    if n == 4:
        i0, i1, i2, i3 = vals
        t0 = tmp(f'{i1} * Math.SQRT2'); t1 = tmp(f'{i1} + {i3}')
        o0 = tmp(f'({t0} + {t1}) * SEC0'); o1 = tmp(f'({t0} - {t1}) * SEC1')
        s02 = tmp(f'{i0} + {i2}'); d02 = tmp(f'{i0} - {i2}')
        return [tmp(f'{s02} + {o0}'), tmp(f'{d02} + {o1}'), tmp(f'{d02} - {o1}'), tmp(f'{s02} - {o0}')]
    half = n // 2
    evens = [vals[2 * i] for i in range(half)]
    odds = [vals[2 * i + 1] for i in range(half)]
    # input1[half - i] += input1[half - i - 1] for i = 1..half-1 (descending, so each adds the original)
    new_odds = list(odds)
    for i in range(1, half):
        k = half - i
        new_odds[k] = tmp(f'{odds[k]} + {odds[k - 1]}')
    new_odds[0] = tmp(f'{odds[0]} * Math.SQRT2')
    a = idct(evens, half, secname)
    b = idct(new_odds, half, secname)
    b = [tmp(f'{b[i]} * SEC{n}[{i}]') for i in range(half)]
    out = [None] * n
    for i in range(half):
        out[i] = tmp(f'{a[i]} + {b[i]}')
        out[n - i - 1] = tmp(f'{a[i]} - {b[i]}')
    return out

print('''/*!
 * Generated by scripts/jxl-idct.py: the inverse 16- and 32-point DCTs of dct.ts, unrolled (its recursion is ported from
 * jxl-oxide, crates/jxl-render/src/vardct/generic/dct.rs; Copyright (c) Wonwoo Choi, MIT License, see
 * THIRD_PARTY_NOTICES.md)
 */

const SEC0 = 0.5411961, SEC1 = 1.306563;
// 1 / (2 cos((2k + 1) pi / 2n))
const secants = (n: number): Float64Array => Float64Array.from({ length: n / 2 }, (_, k) => 1 / Math.cos((2 * k + 1) / (2 * n) * Math.PI) / 2);
const SEC8 = secants(8), SEC16 = secants(16), SEC32 = secants(32);
''')
for n in (16, 32):
    counter[0] = 0; lines.clear()
    vals = [f'v{i}' for i in range(n)]
    out = idct(vals, n, f'SEC{n}')
    print(f'// the inverse {n}-point DCT of buf[o + k * step] in place (generated: dct\'s recursion, unrolled)')
    print(f'export function idct{n}(buf: Float32Array, o: number, step: number): void {{')
    for i in range(n):
        print(f'    const v{i} = buf[o + {i} * step];' if i else '    const v0 = buf[o];')
    for l in lines: print(l)
    for i in range(n):
        print(f'    buf[o + {i} * step] = {out[i]};' if i else f'    buf[o] = {out[0]};')
    print('}')
    print()
