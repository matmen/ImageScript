# Writes src/codecs/vp8-enc-tables.ts: the tables of libwebp's lossy (VP8) encoder that aren't in the decoder's
# tables, read from the C sources of a libwebp checkout (https://chromium.googlesource.com/webm/libwebp, BSD-3-Clause):
#   python scripts/vp8-enc-tables.py path/to/libwebp > src/codecs/vp8-enc-tables.ts
import base64, re, struct, sys

root = sys.argv[1].rstrip('/') + '/'


def table(path, name):
    """the values of a C array, flattened"""
    s = open(root + path).read()
    m = re.search(r'\b' + re.escape(name) + r'\s*(\[[^=]*\])\s*=\s*\{', s)
    i = j = m.end()
    depth = 1
    while depth:
        depth += {'{': 1, '}': -1}.get(s[j], 0)
        j += 1
    body = re.sub(r'//[^\n]*', '', re.sub(r'/\*.*?\*/', '', s[i:j - 1], flags=re.S))
    return [int(x, 0) for x in re.findall(r'-?(?:0x[0-9a-fA-F]+|\d+)', body)]


def ints(name, comment, values):
    rows = [', '.join(str(v) for v in values[i:i + 32]) for i in range(0, len(values), 32)]
    print(f'/** {comment} */\nexport const {name} = [\n    ' + ',\n    '.join(rows) + '\n];\n')


def words(name, comment, values):
    data = base64.b64encode(struct.pack(f'<{len(values)}H', *values)).decode()
    print(f'/** {comment} (16 bit, base64) */\nexport const {name} = \'{data}\';\n')


print('''/*!
 * Generated by scripts/vp8-enc-tables.py from libwebp, don't edit. Copyright (c) 2010 Google Inc., BSD-3-Clause License
 * (see THIRD_PARTY_NOTICES.md)
 */
''')
ints('ENTROPY_COST', 'VP8EntropyCost: the cost of a bit by probability (1/256 bits)', table('src/dsp/cost.c', 'VP8EntropyCost'))
words('LEVEL_FIXED_COSTS', 'VP8LevelFixedCosts: the part of the cost of a level that doesn\'t depend on probabilities',
      table('src/dsp/cost.c', 'VP8LevelFixedCosts'))
ints('LEVEL_CODES', 'VP8LevelCodes[67][2]: the contexts used to code a level (pattern) and their bits',
     table('src/enc/cost_enc.c', 'VP8LevelCodes'))
words('FIXED_COSTS_I4', 'VP8FixedCostsI4[top][left][mode]: the costs of the intra 4x4 modes',
      table('src/enc/cost_enc.c', 'VP8FixedCostsI4'))
ints('BMODES_PROBA', 'kBModesProba[top][left][9]: the probabilities of the intra 4x4 modes (encoder\'s mode order)',
     table('src/enc/tree_enc.c', 'kBModesProba'))
ints('AC_TABLE2', 'kAcTable2: the AC quantizers of the luma DC (Y2) blocks', table('src/enc/quant_enc.c', 'kAcTable2'))
ints('LEVELS_FROM_DELTA', 'kLevelsFromDelta[sharpness][delta]: the filter strength that smooths an edge step',
     table('src/enc/filter_enc.c', 'kLevelsFromDelta'))
